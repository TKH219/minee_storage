Transaction ledgerTransaction({
  String id = 'txn-1',
  String code = 'S-202608-0041',
  TransactionType type = TransactionType.sale,
  DateTime? occurredAt,
  TransactionMoney? money,
  List<TransactionLine>? lines,
  List<TransactionFee> fees = const [],
  String? counterparty,
  PaymentMethod? paymentMethod = PaymentMethod.card,
  WriteOffReason? reason,
  String? reasonNote,
  String? note,
  DateTime? amendedAt,
  DateTime? updatedTime,
}) => Transaction(
  id: id,
  storeId: 'store-1',
  type: type,
  code: code,
  occurredAt: occurredAt ?? DateTime(2026, 8, 26, 9, 12),
  money: money ?? ledgerMoney(),
  lines: lines ?? [ledgerLine()],
  fees: fees,
  counterparty: counterparty,
  paymentMethod: paymentMethod,
  reason: reason,
  reasonNote: reasonNote,
  note: note,
  amendedAt: amendedAt,
  createdTime: DateTime(2026, 8, 26, 9, 12),
  updatedTime: updatedTime ?? DateTime(2026, 8, 26, 9, 12),
);
