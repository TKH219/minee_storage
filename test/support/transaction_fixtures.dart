import 'package:decimal/decimal.dart';

import 'package:mine_storage/domain/entities/entities.dart';

Decimal dec(String value) => Decimal.parse(value);

TransactionLine ledgerLine({
  String id = 'line-1',
  String productId = 'product-1',
  String productName = 'Whole Milk 1L',
  String batchId = 'batch-1',
  String batchCode = 'L-2608-A',
  String quantityDelta = '-2.000',
  String? quantityBefore,
  String unitPrice = '1.80',
  String unitCostSnapshot = '1.10',
  String? batchUnitCost,
  String lineGross = '3.60',
  String lineCost = '2.20',
  DateTime? expiryDate,
  int sortOrder = 0,
}) => TransactionLine(
  id: id,
  transactionId: 'txn-1',
  productId: productId,
  batchId: batchId,
  batchCode: batchCode,
  productName: productName,
  unit: ProductUnit.piece,
  quantityDelta: dec(quantityDelta),
  quantityBefore: quantityBefore == null ? null : dec(quantityBefore),
  unitPrice: dec(unitPrice),
  unitCostSnapshot: dec(unitCostSnapshot),
  batchUnitCost: batchUnitCost == null ? null : dec(batchUnitCost),
  lineGross: dec(lineGross),
  lineCost: dec(lineCost),
  expiryDate: expiryDate,
  sortOrder: sortOrder,
);

TransactionFee ledgerFee({
  String id = 'fee-1',
  String name = 'Freight',
  FeeDirection direction = FeeDirection.sellerCost,
  FeeKind kind = FeeKind.fixed,
  String value = '6.00',
  String computedAmount = '6.00',
}) => TransactionFee(
  id: id,
  transactionId: 'txn-1',
  name: name,
  direction: direction,
  kind: kind,
  value: dec(value),
